export type Dictionary = typeof ZH;

const dicts: Record<Locale, Dictionary> = { zh: ZH, en: EN };

const LocaleContext = createContext<{
  locale: Locale;
  t: Dictionary;
  setLocale: (locale: Locale) => void;
}>({
  locale: "zh",
  t: ZH,
  setLocale: () => undefined,
});

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("zh");

  useEffect(() => {
    const saved = window.localStorage.getItem(KEY);
    if (saved === "en" || saved === "zh") setLocaleState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
    document.title = locale === "zh" ? "合译 — 中英互译" : "Cowork Translation — Chinese–English";
  }, [locale]);

  const value = useMemo(
    () => ({
      locale,
      t: dicts[locale],
      setLocale: (next: Locale) => {
        setLocaleState(next);
        window.localStorage.setItem(KEY, next);
      },
    }),
    [locale],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}

export function domainLabel(t: Dictionary, value: string) {
  return t.domainLabels[value as keyof Dictionary["domainLabels"]] ?? value;
}
